#!/usr/bin/env python3
"""Regenerates Docs/AutomationCommands.md, Docs/Components.md and the component section of Docs/basalt.d.lua
from the engine itself (`basalt help` and `basalt component.types`), so the references never drift from the code.

Usage: python3 scripts/generate_docs.py [--check] [path/to/basalt]   (default: build/bin/basalt)
With --check nothing is written: the script fails (exit 1) when a generated file is out of date (the GeneratedDocs
ctest runs it this way).
"""
import json, os, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
arguments = sys.argv[1:]
check = "--check" in arguments
arguments = [argument for argument in arguments if argument != "--check"]
default = os.path.join(root, "build", "bin", "basalt" + (".exe" if os.name == "nt" else ""))
basalt = arguments[0] if arguments else default

LUA_BEGIN = "-- BEGIN GENERATED: components (scripts/generate_docs.py)"
LUA_END = "-- END GENERATED: components"

def run(command):
    output = subprocess.run([basalt, command], check=True, capture_output=True, text=True).stdout
    response = json.loads(output)
    if not response.get("ok"):
        raise SystemExit(f"basalt {command} failed: {response}")
    return response["result"]

def automation_commands(commands):
    lines = ["# Automation Commands", "",
             "Generated by `scripts/generate_docs.py` from `basalt help` — do not edit by hand.", "",
             "Every command is available through the `basalt` CLI and the editor's TCP server (127.0.0.1:7420).",
             "See `.claude/skills/basalt-make-game/SKILL.md` for the workflow and [MCP.md](MCP.md) for MCP clients.",
             "`basalt help <command>` returns the same `inputSchema` used by request validation and MCP tool discovery.",
             "Commands reject parameters they do not list. In a batch, a request with `\"expectError\": \"<text>\"`",
             "succeeds only if its command fails with an error containing `<text>` (used by tests).", ""]
    group = None
    for command in commands:
        name = command["command"]
        prefix = name.split(".")[0]
        if prefix != group:
            group = prefix
            lines += [f"## {group}", ""]
        lines.append(f"### `{name}`")
        lines.append("")
        lines.append(command["description"])
        if command["params"]:
            lines.append("")
            lines.append("| Parameter | Type / description |")
            lines.append("|-----------|--------------------|")
            for parameter, description in sorted(command["params"].items()):
                lines.append(f"| `{parameter}` | {description} |")
        lines += ["", "<details><summary>Parameter JSON Schema</summary>", "", "```json",
                  json.dumps(command["inputSchema"], indent=2, ensure_ascii=False), "```", "", "</details>", ""]
    return "\n".join(lines) + "\n"

def field_description(component, field):
    kind = component["types"][field]
    if kind.startswith("enum"):
        return f"`{field}` ({kind}: {', '.join(component['enums'][field])})"
    return f"`{field}` ({kind})"

def components_markdown(components):
    lines = ["# Components", "",
             "Generated by `scripts/generate_docs.py` from `basalt component.types` — do not edit by hand.", "",
             "Component data is JSON in scene files, prefabs, `component.set` and Lua `GetComponent/SetComponent`.",
             "Vectors are arrays (`[x, y, z]`), colors are RGB(A) arrays in linear space, rotations are Euler degrees,",
             "asset references are project-relative paths (`Assets/...`) or built-in meshes (`builtin://Cube`).",
             "Field types: `number`, `integer`, `boolean`, `string`, `object`, `entity` (an entity ID, 0 = none),",
             "`enum` (one of the listed names) and arrays of them with their length (`number[3]`).", ""]
    for component in components:
        core = " (always present)" if component["core"] else ""
        lines.append(f"## {component['name']}{core}")
        lines.append("")
        lines.append("Fields: " + ", ".join(field_description(component, field) for field in component["fields"]))
        lines.append("")
    return "\n".join(lines) + "\n"

def lua_type(component, field):
    """The LuaLS type of a field; the LuaTypeDefinitions unit test applies the same mapping."""
    kind = component["types"][field]
    base, _, count = kind.partition("[")
    if base == "enum":
        union = "|".join(f'"{option}"' for option in component["enums"][field])
        return f"({union})[]" if count else union
    scalar = {"number": "number", "integer": "integer", "boolean": "boolean", "string": "string",
              "object": "table", "entity": "integer"}[base]
    return f"{scalar}[]" if count else scalar

def lua_components(components):
    lines = [LUA_BEGIN, "", "---@alias ComponentName"]
    lines += [f'---| "{component["name"]}"' for component in components]
    for component in components:
        lines += ["", f"---{component['name']} data as Entity:GetComponent returns it and SetComponent/AddComponent accept it.",
                  f"---@class {component['name']}Component"]
        lines += [f"---@field {field} {lua_type(component, field)}" for field in component["fields"]]
    lines += ["", "---Returns a copy of the component's fields (vectors as arrays, rotations in Euler degrees, entity references",
              "---as IDs), or nil when the entity does not have the component.",
              "---@param name ComponentName", "---@return table?"]
    lines += [f'---@overload fun(self: Entity, name: "{component["name"]}"): {component["name"]}Component?' for component in components]
    lines += ["function Entity:GetComponent(name) end", LUA_END]
    return "\n".join(lines)

def replace_lua_section(text, section):
    begin = text.find(LUA_BEGIN)
    end = text.find(LUA_END)
    if begin < 0 or end < begin:
        raise SystemExit(f"Docs/basalt.d.lua: missing the '{LUA_BEGIN}' / '{LUA_END}' markers")
    return text[:begin] + section + text[end + len(LUA_END):]

def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()

commands = run("help")["commands"]
components = run("component.types")["components"]
lua_path = os.path.join(root, "Docs", "basalt.d.lua")
outputs = {
    os.path.join(root, "Docs", "AutomationCommands.md"): automation_commands(commands),
    os.path.join(root, "Docs", "Components.md"): components_markdown(components),
    lua_path: replace_lua_section(read(lua_path).replace("\r\n", "\n"), lua_components(components)),
}

stale = []
for path, text in outputs.items():
    # Checkouts may convert line endings (Windows); only the content matters.
    current = read(path).replace("\r\n", "\n") if os.path.exists(path) else None
    if current == text:
        continue
    if check:
        stale.append(os.path.relpath(path, root))
    else:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
if stale:
    raise SystemExit("Out of date: " + ", ".join(stale) + ". Run 'python3 scripts/generate_docs.py' and commit the result.")
print("Generated docs are up to date." if check else "Docs regenerated.")
